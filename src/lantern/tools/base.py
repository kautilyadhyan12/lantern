"""What a tool is, what a call to it looks like, and what it gives back."""

from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, ClassVar, Literal, Protocol

from pydantic import BaseModel, ConfigDict, Field

from lantern.models import Triple
from lantern.search import Hit

ToolKind = Literal["search", "read", "record"]


class ToolError(Exception):
    """A tool could not do its job; the message says what happened in plain words."""


class ToolArgs(BaseModel):
    """Base for a tool's arguments: unknown names are refused and text is trimmed."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)


class ToolCall(BaseModel):
    """One call proposed by the researcher (or, for now, by the fixed research rounds)."""

    tool: str
    args: dict[str, object]
    question_ref: str
    why: str = Field(max_length=200)


@dataclass(frozen=True)
class SourceDraft:
    """Something worth preserving. The investigation turns it into a Source with a ref."""

    url: str
    title: str | None
    published: str | None
    body: bytes
    text: str
    kind: Literal["page", "post", "record", "image"]
    origin: str
    archive_url: str | None = None
    archived_at: datetime | None = None
    record_claims: tuple[str, ...] = ()  # statements generated by code (records only)
    grade: tuple[str, str] | None = None  # (Admiralty grade, why), set by record tools
    # Relations the record lists, each with the index of the record claim that states it.
    relations: tuple[tuple[int, Triple], ...] = ()


@dataclass
class ToolResult:
    hits: list[Hit] = field(default_factory=list)  # transient: this step only, never stored
    sources: list[SourceDraft] = field(default_factory=list)
    summary: str = ""  # one plain line for the log and the case file


@dataclass
class ToolContext:
    """What the tools of one run share about the sites they meet."""

    refusing: set[str] = field(default_factory=set)  # sites that refused Lantern once
    robots_no: set[str] = field(default_factory=set)  # robots.txt said no: never archived


@dataclass
class RunBudget:
    """Calls left in this run, in total and per kind of tool."""

    tool_calls: int
    searches: int
    pages: int
    records: int

    def left(self, kind: ToolKind) -> int:
        per_kind = {"search": self.searches, "read": self.pages, "record": self.records}
        return max(0, min(self.tool_calls, per_kind[kind]))

    def spend(self, kind: ToolKind) -> None:
        self.tool_calls -= 1
        if kind == "search":
            self.searches -= 1
        elif kind == "read":
            self.pages -= 1
        else:
            self.records -= 1


class Tool(Protocol):
    name: ClassVar[str]  # "web_search", "read_page", ...
    description: ClassVar[str]  # shown to the model in the tool menu
    args_model: ClassVar[type[BaseModel]]
    kind: ClassVar[ToolKind]
    rate_key: ClassVar[str]  # calls with the same key are paced together
    min_interval: ClassVar[float]  # seconds between calls with this key

    # `args` is an instance of `args_model`, already validated by the gateway; each tool
    # declares it as its own args model.
    async def run(self, args: Any, ctx: ToolContext) -> ToolResult: ...
