"""Official sanctions lists: the US Treasury OFAC SDN list and the UN Security Council
Consolidated List.

Each list is downloaded at most once a day, saved with its sha256, and older copies are
deleted. A name matches when it has the same words as a listed name or alias, in any order,
ignoring case, accents and punctuation; there is no fuzzy matching, so similar names never
match. Each matching entry becomes a record source graded A, with statements generated by
code. Only what an investigation needs is kept: names, aliases, programmes and links.
Dates of birth, passport and ID numbers, addresses and family details are never kept.

Checked 2026-11-05: OFAC `SDN.CSV` 5.8 MB and `ALT.CSV` 1.1 MB (no header; "-0-" means
empty), US government data, no key or stated rate limit. UN `consolidated.xml` 2.2 MB, no
key or stated rate limit; Lantern keeps the file locally and does not redistribute it.
"""

import asyncio
import csv
import hashlib
import io
import json
import re
from collections.abc import Callable
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import ClassVar, Protocol
from xml.etree import ElementTree  # nosec B405  # DTDs and entities are refused before parsing

from pydantic import BaseModel, Field

from lantern.egress import FetchError, Page
from lantern.models import Triple, now
from lantern.text import name_words
from lantern.tools.base import SourceDraft, ToolArgs, ToolContext, ToolError, ToolKind, ToolResult

OFAC = "https://sanctionslistservice.ofac.treas.gov/api/PublicationPreview/exports"
UN = "https://scsanctions.un.org/resources/xml/en/consolidated.xml"
LIST_BYTES = 20_000_000
MAX_MATCHES = 5
MAX_ALIASES = 30
GRADE = ("A", "Official sanctions list")


class DataFetcher(Protocol):
    async def fetch_data(
        self, url: str, accept: tuple[str, ...], *, max_bytes: int, seconds: float = 60.0
    ) -> Page: ...


class NameArgs(ToolArgs):
    name: str = Field(min_length=2, max_length=200)


@dataclass(frozen=True)
class Entry:
    """One listed person, organisation, vessel or aircraft, with only what Lantern keeps."""

    listing: str  # "OFAC" or "UN"
    ref: str  # OFAC entry number or UN reference number
    name: str
    kind: str  # entity, individual, vessel or aircraft
    programmes: tuple[str, ...]
    aliases: tuple[str, ...]
    links: tuple[str, ...] = ()
    reason: str = ""  # the UN listing note, for entities only
    listed_on: str = ""


def name_key(name: str, *, loose: bool = False) -> str:
    """The words of a name in order, so word order and punctuation never matter. `loose`
    also drops one-letter joining words, so "Lashkar-e-Taiba" meets "Lashkar-i-Taiba";
    it is used for organisations only, because people's initials must still count."""
    words = name_words(name)
    return " ".join(sorted(word for word in words if not loose or len(word) > 1))


def _value(cell: str) -> str:
    return "" if cell.strip() == "-0-" else cell.strip()


def ofac_entries(sdn: bytes, alt: bytes) -> list[Entry]:
    aliases: dict[str, list[str]] = {}
    for row in csv.reader(io.StringIO(alt.decode("utf-8", "replace"))):
        if len(row) >= 4 and _value(row[3]):
            aliases.setdefault(row[0].strip(), []).append(_value(row[3]))
    entries = []
    for row in csv.reader(io.StringIO(sdn.decode("utf-8", "replace"))):
        if len(row) < 12 or not _value(row[1]):
            continue
        number, remarks = row[0].strip(), _value(row[11])
        programmes = tuple(p.strip("[] ") for p in _value(row[3]).split("] [") if p.strip("[] "))
        named = aliases.get(number, []) + re.findall(r"a\.k\.a\. '([^']+)'", remarks)
        links = re.findall(r"Linked To: ([^;]+?)\.?(?:;|$)", remarks)
        entries.append(
            Entry(
                listing="OFAC",
                ref=number,
                name=_value(row[1]),
                kind=_value(row[2]) or "entity",
                programmes=programmes,
                aliases=tuple(dict.fromkeys(named)),
                links=tuple(dict.fromkeys(link.strip() for link in links)),
            )
        )
    return entries


def un_entries(xml: bytes) -> list[Entry]:
    if b"<!DOCTYPE" in xml or b"<!ENTITY" in xml:
        raise ToolError("The UN list contained a document type declaration; it was not read.")
    try:
        root = ElementTree.fromstring(xml)  # noqa: S314  # nosec B314  # DTDs refused above
    except ElementTree.ParseError as error:
        raise ToolError("The UN list could not be read: it is not valid XML.") from error
    entries = []
    for kind, tag in (("individual", "INDIVIDUAL"), ("entity", "ENTITY")):
        for node in root.iter(tag):
            parts = ("FIRST_NAME", "SECOND_NAME", "THIRD_NAME", "FOURTH_NAME")
            name = " ".join(text for part in parts if (text := (node.findtext(part) or "").strip()))
            aliases = [
                alias.strip()
                for item in node.findall(f"{tag}_ALIAS")
                if (alias := item.findtext("ALIAS_NAME") or "")
            ]
            note = " ".join((node.findtext("COMMENTS1") or "").split())
            entries.append(
                Entry(
                    listing="UN",
                    ref=(node.findtext("REFERENCE_NUMBER") or "").strip(),
                    name=name,
                    kind=kind,
                    programmes=tuple(filter(None, [(node.findtext("UN_LIST_TYPE") or "").strip()])),
                    aliases=tuple(dict.fromkeys(aliases)),
                    # Notes on individuals often name relatives: they are never kept.
                    reason=note.split("INTERPOL")[0].strip() if kind == "entity" else "",
                    listed_on=(node.findtext("LISTED_ON") or "").strip(),
                )
            )
    return entries


class DailyFile:
    """An official file downloaded at most once a day; only the latest copy is kept."""

    def __init__(self, folder: Path, name: str, url: str, accept: tuple[str, ...]) -> None:
        self.folder, self.name, self.url, self.accept = folder, name, url, accept

    async def get(self, fetcher: DataFetcher, today: date) -> tuple[bytes, str]:
        """The file's bytes and sha256, downloading it only if today's copy is missing."""
        path = self.folder / f"{self.name}-{today.isoformat()}"
        if await asyncio.to_thread(path.exists):
            body = await asyncio.to_thread(path.read_bytes)
        else:
            try:
                page = await fetcher.fetch_data(self.url, self.accept, max_bytes=LIST_BYTES)
            except FetchError as error:
                raise ToolError(f"The {self.name} list could not be downloaded: {error}") from error
            body = page.body
            await asyncio.to_thread(self._replace, path, body)
        return body, hashlib.sha256(body).hexdigest()

    def _replace(self, path: Path, body: bytes) -> None:
        self.folder.mkdir(parents=True, exist_ok=True)
        for old in self.folder.glob(f"{self.name}-*"):
            old.unlink()  # retention: one day's copy only
        path.write_bytes(body)


@dataclass(frozen=True)
class Listing:
    title: str
    url: str  # the file, for the record of where the entry came from
    sha256: str
    day: str
    entries: dict[str, list[Entry]]  # name key → entries


def record(entry: Entry, listing: Listing) -> SourceDraft:
    """A record source for one entry: code-generated statements, nothing else."""
    if entry.listing == "OFAC":
        url = f"https://sanctionssearch.ofac.treas.gov/Details.aspx?id={entry.ref}"
        where = f"the US Treasury OFAC SDN list (entry {entry.ref})"
    else:
        url = f"{UN}#{entry.ref}"
        where = f"the UN Security Council Consolidated List (reference {entry.ref})"
    programmes = f" under {', '.join(entry.programmes)}" if entry.programmes else ""
    since = f", listed on {entry.listed_on}" if entry.listed_on else ""
    if entry.kind == "individual":
        listed = (
            f"An individual named {entry.name} is on {where}{programmes}{since}. A matching "
            "name alone does not show that this is the same person as in the evidence."
        )
    else:
        listed = f"{entry.name} is on {where} as {'an' if entry.kind[0] in 'aeiou' else 'a'}"
        listed += f" {entry.kind}{programmes}{since}."
    claims = [listed]
    if entry.aliases:
        names = "; ".join(entry.aliases[:MAX_ALIASES])
        claims.append(f"The list also names {entry.name} as: {names}.")
    claims += [f"The list links {entry.name} to {link}." for link in entry.links]
    if entry.reason:
        claims.append(f"The UN listing of {entry.name} notes: {entry.reason}")
    relations = _relations(entry, claims)
    origin = f"Source: {listing.title}, {listing.url}, downloaded {listing.day}, sha256 "
    text = "\n".join([f"{origin}{listing.sha256}.", *claims])
    kept = {key: value for key, value in vars(entry).items() if value}
    body: dict[str, object] = {"list": listing.title, "file": listing.url}
    body["file_sha256"] = listing.sha256
    body |= {"downloaded": listing.day, "entry": kept}
    return SourceDraft(
        url=url,
        title=f"{listing.title}: {entry.name}",
        published=entry.listed_on or None,
        body=json.dumps(body, ensure_ascii=False, sort_keys=True).encode(),
        text=text,
        kind="record",
        origin="ofac.treas.gov" if entry.listing == "OFAC" else "un.org",
        record_claims=tuple(claims),
        grade=GRADE,
        relations=relations,
    )


LISTERS = {"OFAC": "US Treasury OFAC", "UN": "UN Security Council"}
# "Associated with Hafiz Muhammad Saeed (QDi.263)": a name and its UN reference number.
ASSOCIATED = re.compile(
    r"(?:with|and|,)\s+([A-Z][\w'.-]*(?:\s[\w'.-]+){0,6}?)\s\(([A-Z]{2}[ie]\.\d+)\)"
)


def _relations(entry: Entry, claims: list[str]) -> tuple[tuple[int, Triple], ...]:
    """The record's links, generated by code: designated by the list's authority, and
    linked to each "Linked To" entry. Vessels and aircraft get none."""
    if entry.kind not in {"entity", "individual"}:
        return ()
    ids = [f"{entry.listing.lower()}:{entry.ref}"]
    kind = "person_public_role" if entry.kind == "individual" else "organisation"
    subject = {"name": entry.name, "kind": kind, "ids": ids, "aliases": list(entry.aliases)}
    lister = {"name": LISTERS[entry.listing], "kind": "organisation", "ids": [entry.listing]}
    found = [(0, {"subject": subject, "relation": "designated_by", "object": lister})]
    for link in entry.links:
        index = claims.index(f"The list links {entry.name} to {link}.")
        target = {"name": link, "kind": "organisation"}
        found.append((index, {"subject": subject, "relation": "linked_to", "object": target}))
    if entry.reason:  # the UN note names associated entries by their reference numbers
        index = claims.index(f"The UN listing of {entry.name} notes: {entry.reason}")
        for name, ref in ASSOCIATED.findall(entry.reason):
            kind = "person_public_role" if ref[2] == "i" else "organisation"
            other = {"name": name.strip(), "kind": kind, "ids": [f"un:{ref}"]}
            found.append((index, {"subject": other, "relation": "linked_to", "object": subject}))
    return tuple(
        (index, Triple.model_validate({**data, "claim_refs": [], "basis": "record"}))
        for index, data in found
    )


class SanctionsSearch:
    name: ClassVar[str] = "sanctions_search"
    description: ClassVar[str] = (
        "Check a name of an organisation or person from the case file against the official "
        "US (OFAC SDN) and UN Security Council sanctions lists, including listed aliases. "
        "Exact names only (word order and punctuation ignored). A match on a person's name "
        "alone does not prove it is the same person."
    )
    args_model: ClassVar[type[BaseModel]] = NameArgs
    kind: ClassVar[ToolKind] = "record"
    rate_key: ClassVar[str] = "sanctions"
    min_interval: ClassVar[float] = 0.0

    def __init__(
        self, fetcher: DataFetcher, folder: Path, today: Callable[[], date] = lambda: now().date()
    ) -> None:
        self._fetcher, self._today = fetcher, today
        csv_types = ("text/csv", "text/plain", "application/octet-stream")
        xml_types = ("application/xml", "text/xml")
        self._files = {
            "OFAC-SDN": DailyFile(folder, "OFAC-SDN", f"{OFAC}/SDN.CSV", csv_types),
            "OFAC-ALT": DailyFile(folder, "OFAC-ALT", f"{OFAC}/ALT.CSV", csv_types),
            "UN": DailyFile(folder, "UN", UN, xml_types),
        }
        self._lists: list[Listing] | None = None
        self._lock = asyncio.Lock()

    async def run(self, args: NameArgs, _ctx: ToolContext) -> ToolResult:
        lists = await self._load()
        keys = (name_key(args.name), f"~{name_key(args.name, loose=True)}")
        drafts = []
        for listing in lists:
            matches = [entry for key in keys for entry in listing.entries.get(key, [])]
            drafts += [record(entry, listing) for entry in dict.fromkeys(matches)][:MAX_MATCHES]
        found = "; ".join(f"{item.title} {item.url}" for item in drafts)
        if not drafts:
            summary = f"Sanctions lists: no entry named “{args.name}” on the OFAC SDN or UN lists."
        else:
            summary = f"Sanctions lists: {len(drafts)} entries named “{args.name}” ({found})."
        return ToolResult([], drafts, summary)

    async def _load(self) -> list[Listing]:
        async with self._lock:
            if self._lists is None:
                day = self._today()
                sdn, sdn_sha = await self._files["OFAC-SDN"].get(self._fetcher, day)
                alt, _ = await self._files["OFAC-ALT"].get(self._fetcher, day)
                xml, un_sha = await self._files["UN"].get(self._fetcher, day)
                self._lists = [
                    _listing(
                        "US Treasury OFAC SDN list",
                        f"{OFAC}/SDN.CSV",
                        sdn_sha,
                        day,
                        ofac_entries(sdn, alt),
                    ),
                    _listing(
                        "UN Security Council Consolidated List", UN, un_sha, day, un_entries(xml)
                    ),
                ]
            return self._lists


def _listing(title: str, url: str, sha256: str, day: date, entries: list[Entry]) -> Listing:
    index: dict[str, list[Entry]] = {}  # exact keys, and "~" loose keys for non-individuals
    for entry in entries:
        names = (entry.name, *entry.aliases)
        keys = [name_key(name) for name in names]
        if entry.kind != "individual":
            keys += [f"~{name_key(name, loose=True)}" for name in names]
        for key in dict.fromkeys(keys):
            if key.strip("~"):
                index.setdefault(key, []).append(entry)
    return Listing(title, url, sha256, day.isoformat(), index)
